package org.hongen.sonylutprobe;

import java.io.*;
import java.nio.file.*;
import java.util.*;

public final class LutNameTest {
    private static void require(boolean value,String why){if(!value)throw new AssertionError(why);}
    private static final LutLibrary.Verifier VALID=new LutLibrary.Verifier(){public int inspect(File file){return 33;}};
    private static File cube(File dir,String name,String title,String body)throws Exception{
        File f=new File(dir,name);String head=title==null?"":"TITLE \""+title+"\"\r\n";
        Files.write(f.toPath(),(head+"LUT_3D_SIZE 33\r\n# "+body+"\r\n").getBytes("UTF-8"));return f;
    }
    public static void main(String[] args)throws Exception {
        for(String t:new String[]{"Generated by Resolve","Generated by Koji Cubev.taobao.com","Created with Lutify.me","exported from Photoshop","Untitled","3D LUT",""})
            require(LutLibrary.genericTitle(t),"generic: "+t);
        for(String t:new String[]{"warm_chrome","Kodak Portra 400","Generated Look","Fuji C200"})
            require(!LutLibrary.genericTitle(t),"meaningful: "+t);
        File base=Files.createTempDirectory("sony-names-").toFile();
        try{
            File luts=new File(base,"LUTS");luts.mkdir();File root=new File(base,"library");
            LutLibrary library=new LutLibrary(root);
            String a=library.importFile(cube(luts,"FUJI3513.CUB","Generated by Resolve","a"),null,"custom",VALID).entry.name;
            String b=library.importFile(cube(luts,"FUJI3514.CUB","Generated by Resolve","b"),null,"custom",VALID).entry.name;
            String c=library.importFile(cube(luts,"KOJI.CUB","Generated by Koji Cubev.taobao.com","c"),null,"custom",VALID).entry.name;
            require(a.equals("FUJI3513")&&b.equals("FUJI3514")&&c.equals("KOJI"),"exporter boilerplate falls back to file names: "+a+","+b+","+c);
            require(library.importFile(cube(luts,"WCHROME.CUB","warm_chrome","d"),null,"custom",VALID).entry.name.equals("warm_chrome"),"meaningful TITLE kept");
            require(library.importFile(cube(luts,"NOTITLE.CUB",null,"e"),null,"custom",VALID).entry.name.equals("NOTITLE"),"missing TITLE uses file name");
            String f1=library.importFile(cube(luts,"FUJIA.CUB","Fuji","f1"),null,"custom",VALID).entry.name;
            String f2=library.importFile(cube(luts,"FUJIB.CUB","Fuji","f2"),null,"custom",VALID).entry.name;
            require(f1.equals("Fuji")&&f2.equals("Fuji · FUJIB"),"different contents never share a name: "+f2);
            Set<String> names=new HashSet<String>();for(LutLibrary.Entry e:library.entries())require(names.add(e.name.toLowerCase(Locale.US)),"unique library names");

            // An entry imported by an earlier version still carries the boilerplate name.
            File legacySource=cube(luts,"SLOG3.CUB","Generated by Resolve","legacy");
            LutLibrary.Entry legacy=library.importFile(legacySource,null,"custom",VALID).entry;
            File meta=new File(legacy.file.getParentFile(),"ENTRY.DAT");Properties p=LutLibrary.readProperties(meta);
            p.setProperty("name","Generated by Resolve");LutLibrary.writeProperties(meta,p);
            require(library.find(legacy.id).name.equals("Generated by Resolve"),"legacy name reproduced");
            byte[] committed=Files.readAllBytes(meta.toPath());
            LutLibrary.Imported again=library.importFile(legacySource,null,"custom",VALID);
            require(!again.added&&again.entry.name.equals("SLOG3"),"re-import corrects a legacy boilerplate name");
            require(new LutLibrary(root).find(legacy.id).name.equals("SLOG3"),"corrected name persists");
            require(Arrays.equals(committed,Files.readAllBytes(meta.toPath())),"commit marker never rewritten");
            require(!new File(legacy.file.getParentFile(),"NAME.TMP").exists(),"no staging file left");
            File override=new File(legacy.file.getParentFile(),"NAME.DAT");Files.write(override.toPath(),new byte[0]);
            require(library.find(legacy.id).name.equals("Generated by Resolve"),"empty override falls back to committed name");
            System.out.println("PASS LUT names: exporter boilerplate, missing TITLE, duplicate titles, legacy re-import correction, override fallback");
        }finally{delete(base);}
    }
    private static void delete(File f){File[] children=f.listFiles();if(children!=null)for(File child:children)delete(child);f.delete();}
}
